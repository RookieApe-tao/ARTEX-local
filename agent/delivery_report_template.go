const DeliveryReportWritingRules = DeliveryReportRuntimeGuidance + DeliveryReportStyleGuidance + `

报告头只保留一个一级标题和一行 CVSS 4.0 信息：
# 系统或模块 功能或接口 缺陷：实际后果
CVSS 4.0：完整 Base 向量 评分 分数（等级）
一级标题就是漏洞名称，不要另写“漏洞名称”字段。CVSS 向量须与保存参数一致；尖括号占位符不得留在成稿中。

二级标题固定为以下五节，顺序不可改变：

## 描述
用一段短文说明漏洞、必要权限或条件、实际观察到的结果和影响。自然说明评分对应的权限和实际影响，不用“定级依据为”等套句，不添加三级标题。只有状态码或响应头时，不得称为未鉴权接口或数据泄露；证据不足时明确写待核实，不把线索写成已确认漏洞。

## 修复建议
给出针对当前问题的具体修复和修复后的预期行为。证据不足以确认问题时，先要求补齐证据，确认后再写代码修复方向；不猜源码或配置。

## 测试过程
先写“测试时间：”并按“YYYY-MM-DD HH:mm:ss（北京时间）”格式给出执行记录中的北京时间；没有记录时写“测试时间：未记录”。注明实际执行工具和关键参数；记录没有说明时写“执行工具：未记录”，不能把建议复测工具写成已使用。按实际顺序写最短复现步骤，给出必要账号或会话、参数、结果和判据。HTTP 问题必须逐字出现“Burp Repeater”。实际没有使用时写“Burp Repeater 未实际使用，复测未验证”，并说明如何将真实请求放入 Repeater、使用授权会话、改哪个参数、比较什么结果；步骤只能标成建议。不要更改合成标记头来冒充切换账号。若漏洞依赖并发，说明 Repeater 逐条重放只能核对重复处理，不能复现或确认并发；并发复测须使用执行记录中实际用过的工具，不得编造 Repeater 的多线程功能或界面控件。
用简短句子列出失败尝试和未验证项；没有失败记录时写“未取得失败尝试记录”。不添加三级标题。

## 攻击链路
只写一个简短中文树形链路，按证据连接已知入口、身份条件、请求或命令、实际响应和影响；由平台添加 text 代码围栏。除接口、字段名和原始值外，不写 attacker、result、e.g. 等英文说明词，不输出“text”标签或方括号说明。不要用箭头或流水账代替树形分支。HTTP 方法与路径单独成行。未知页面、前端动作或服务端实现不得补造。材料不完整时只画已知步骤并标明缺口。

## 证据说明
简短说明材料来自哪里、HTTP 请求与响应是否已附加、还有什么缺失。不重复测试步骤，不添加三级标题。非 HTTP 问题只说明命令和输出的来源或位置，不提 HTTP 请求与响应，并说明 Burp 不适用。

保存前检查章节顺序、CVSS、攻击链以及证据是否对应同一漏洞。不要为满足格式补造工具、参数、时间或结果。`
