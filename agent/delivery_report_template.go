const DeliveryReportWritingRules = DeliveryReportRuntimeGuidance + DeliveryReportStyleGuidance + `

报告头只保留一个一级标题和一行 CVSS 4.0 信息：
# 系统或模块 功能或接口 缺陷：实际后果
CVSS 4.0：完整 Base 向量 评分 分数（等级）
一级标题就是漏洞名称，不要另写“漏洞名称”字段。CVSS 向量须与保存参数一致；尖括号占位符不得留在成稿中。

二级标题固定为以下五节，顺序不可改变：

## 描述
用短文说明问题、必要权限或条件和实际业务结果。材料不足时说明尚待核实的结论，不把线索写成已确认漏洞。
### 定级依据
用一两句说明评分对应的权限条件和已观察影响，不重复 CVSS 向量或扩展未验证后果。

## 修复建议
给出针对当前问题的具体修复和修复后的预期行为。证据不足以确认问题时，先要求补齐证据，确认后再写代码修复方向；不猜源码或配置。

## 测试过程
### 发现过程与攻击思路
写最短可复现步骤，保留必要身份条件、请求或命令、关键参数、操作顺序和实际判据。只写理解漏洞所需的执行信息；完整工具台账放入详细报告。影响先后顺序时给出北京时间；其他时间不逐项堆列。
### 失败尝试与未验证项
简短列出会影响结论的实际失败和未验证边界。没有相关记录时，不编造，也不为填满栏目堆叠“未取得记录”。
### Burp 复现
HTTP 漏洞写 Burp Repeater 的实际使用情况；未使用时给出建议复测步骤并标记未验证。非 HTTP 问题说明 Burp 不适用。协议未确认时说明缺口，不猜协议或请求格式。

## 攻击链路
只写一个简短中文树形链路，按证据连接已知入口、身份条件、请求或命令、实际响应和影响；由平台添加 text 代码围栏。除接口、字段名和原始值外，不写 attacker、result、e.g. 等英文说明词，不输出“text”标签或方括号说明。不要用箭头或流水账代替树形分支。HTTP 方法与路径单独成行。未知页面、前端动作或服务端实现不得补造。材料不完整时只画已知步骤并标明缺口。

## 证据说明
简短说明材料来源、完整性和缺口。已绑定请求与响应由平台原文附加；正文只引用一次。平台外材料仅在有完整内容时按真实来源引用。非 HTTP 问题引用实际命令和输出，不伪造 HTTP 报文。
### 复测标准
给出能够判定修复成功的最小观察条件。只描述实际可核对的行为，不写未经执行的复测结果。

保存前检查固定结构、CVSS 与保存参数一致、攻击链有树形结构、证据版本有效。`
