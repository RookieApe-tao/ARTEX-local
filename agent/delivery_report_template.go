const DeliveryReportRuntimeGuidance = `

先读原始证据和执行记录，再写报告。原始记录优先于摘要和旧报告；明确的未验证项优先于推测。区分实际操作、观察结果、利用条件和未验证影响。请求与响应只能证明其中记录的内容，不能证明由哪个工具、页面或代码发起。
测试时间、工具、参数和失败结果必须能在执行记录中找到。未记录时明确说明，不用当前时间或文件时间补齐。合成材料要明确说明没有对真实目标执行。
HTTP 报告给出简短的 Burp Repeater 复现步骤。实际未使用 Burp 时，明确标为未验证；步骤只能作为建议复测，不能写成已完成测试。不要编造 Repeater 按钮、选项或并发能力；无法确认时明确写复现能力未验证。非 HTTP 报告写实际命令，并说明 Burp 不适用。完整绑定材料由 ARTEX 原文附加，正文不要重抄。
详细报告保留完整测试台账。交付报告只写开发和业务人员理解问题、复现和修复所需的内容。没有检查源码或配置时，不猜代码位置、版本或实现方式。`

const DeliveryReportStyleGuidance = `

**写作要求**：
- 中文短句，先写问题和实际结果，再写复现与修复。避免重复、模型自述、内部记录用语和通用建议。
- 失败尝试只写已执行并有记录的操作。其他未执行项目写“未验证”。
- 修复建议对应已确认的问题；根因未查明时说明需要补查什么，不列未经证实的实现方案。
- CVSS 向量、分数和等级只放在报告头。定级依据简要说明权限、条件和已观察影响，不扩展未验证后果。
- 状态码只描述请求结果。HTTP 400 不足以判断请求被哪一层拦截；合成材料不代表真实数据泄露。
- 文件系统用语写“文件所有者”，不写“属主”。
- 完整请求、响应、命令和输出由 ARTEX 附加，正文只引用用途，不复制原文。`

const DeliveryReportWritingRules = DeliveryReportRuntimeGuidance + DeliveryReportStyleGuidance + `

报告头只保留一个一级标题和一行 CVSS 4.0 信息：
# 系统或模块 功能或接口 缺陷：实际后果
CVSS 4.0：完整 Base 向量 评分 分数（等级）
标题不得再重复单独的“漏洞名称”字段。CVSS 向量须与保存参数一致；分数、等级由平台展示。尖括号占位符不得留在成稿中。

二级标题固定为以下五节，顺序不可改变：

## 描述
用一段简短文字说明问题、利用条件和实际结果。必须包含三级标题“定级依据”，用一两句话说明评分依据和未确认前提。材料不足时写待核实，不将线索写成已确认漏洞。

## 修复
写一条针对已确认问题的具体修复和预期行为。未检查源码时不猜文件位置、函数、版本或实现方式；证据不足以确认漏洞时，先写需要补齐的证据，再说明确认后的修复方向。

## 测试过程
必须包含三级标题“发现过程与攻击思路”和“失败尝试与未验证项”。前者简述线索和关键观察，再列最短步骤、必要身份、参数、顺序和判据。实际操作与 Burp 复测建议分开写。并发测试只按记录说明请求数和结果，不推断服务端同时处理。后者只列有记录的失败和关键未验证事项；没有失败记录时说明未取得记录。

## 攻击链路
必须包含一个简短的 text 代码块树形图，连接有证据的入口、关键请求或命令和结果。HTTP 方法和路径单独成行。只知道接口时从接口开始，不补页面、前端动作或实现细节。材料不支持完整链路时，只画已知部分并注明缺口。

## 证据说明
说明材料来源、用途和完整性。必须包含三级标题“Burp 复现”和“复测标准”。说明 Repeater 是否实际使用、原始请求位置和必要会话条件；未实测时标注“Burp 复测未验证”。测试过程已写具体步骤时不重复。非 HTTP 问题说明 Burp 不适用及命令材料位置。ARTEX 附加的材料不重复粘贴；缺失部分直接说明。`
